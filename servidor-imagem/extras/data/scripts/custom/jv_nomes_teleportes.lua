-- indice por quadrados de 16x16 para achar rapido os teleportes perto de cada jogador
local GRADE = 16
local indice = {}
for _, t in ipairs(NOMES) do
	local k = t[3] * 100000000 + math.floor(t[1] / GRADE) * 10000 + math.floor(t[2] / GRADE)
	local lista = indice[k]
	if not lista then lista = {}; indice[k] = lista end
	lista[#lista + 1] = {pos = Position(t[1], t[2], t[3]), texto = t[4]}
end

local evento = GlobalEvent("JVNomesTeleportes")
function evento.onThink(interval)
	for _, player in ipairs(Game.getPlayers()) do
		local p = player:getPosition()
		local gx, gy = math.floor(p.x / GRADE), math.floor(p.y / GRADE)
		for dx = -1, 1 do
			for dy = -1, 1 do
				local lista = indice[p.z * 100000000 + (gx + dx) * 10000 + (gy + dy)]
				if lista then
					for _, t in ipairs(lista) do
						if math.abs(t.pos.x - p.x) <= 8 and math.abs(t.pos.y - p.y) <= 6 then
							player:say(t.texto, TALKTYPE_MONSTER_SAY, false, player, t.pos)
						end
					end
				end
			end
		end
	end
	return true
end
evento:interval(3500)
evento:register()
